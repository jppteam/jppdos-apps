# Cyrillic letters that are visually the same as a Latin one. Aliasing keeps the
# table smaller and, more usefully, keeps the two from drifting apart.
ALIAS = {
    'А': 'A', 'В': 'B', 'Е': 'E', 'К': 'K', 'М': 'M', 'Н': 'H', 'О': 'O',
    'Р': 'P', 'С': 'C', 'Т': 'T', 'Х': 'X',
    'а': 'a', 'е': 'e', 'о': 'o', 'р': 'p', 'с': 'c', 'у': 'y', 'х': 'x',
}

# The glyph drawn for any codepoint the font does not cover — a hollow box, so
# unsupported text is visibly unsupported rather than invisible.
NOTDEF = '...../#####/#...#/#...#/#...#/#####/...../'.rstrip('/')


def parse(art):
    rows = art.split('/')
    assert len(rows) == H, f"expected {H} rows, got {len(rows)}: {art!r}"
    for r in rows:
        assert len(r) == W, f"expected {W} cols, got {len(r)}: {r!r}"
    # Column-major: one byte per column, bit 0 = top row.
    cols = []
    for x in range(W):
        b = 0
        for y in range(H):
            if rows[y][x] == '#':
                b |= 1 << y
        cols.append(b)
    return cols


def build():
    """Returns (entries, notdef) where entries is a sorted list of (cp, cols)."""
    glyphs = {}
    for ch, art in ASCII.items():
        glyphs[ord(ch)] = parse(art)
    for ch, art in CYR.items():
        glyphs[ord(ch)] = parse(art)
    for ch, src in ALIAS.items():
        assert src in ASCII, f"alias target {src!r} not in ASCII table"
        glyphs[ord(ch)] = parse(ASCII[src])

    # Coverage is asserted rather than assumed: a single missing letter shows up
    # only as one wrong character in a message, which is easy to miss by eye.
    missing = [cp for cp in range(0x20, 0x7F) if cp not in glyphs]
    assert not missing, f"missing ASCII: {[hex(c) for c in missing]}"
    cyr = list(range(0x410, 0x450)) + [0x401, 0x451]
    missing = [cp for cp in cyr if cp not in glyphs]
    assert not missing, \
        f"missing Cyrillic: {[chr(c) + ' U+%04X' % c for c in missing]}"
    # No two letters should share a bitmap unless it was a deliberate alias,
    # which would mean a glyph was pasted and not edited.
    seen = {}
    intended = {ord(k): ord(v) for k, v in ALIAS.items()}
    for cp, cols in glyphs.items():
        key = tuple(cols)
        if key in seen and cp not in intended and seen[key] not in intended.values():
            prev = seen[key]
            # Blank cells legitimately repeat (space and non-breaking variants).
            if any(cols):
                raise AssertionError(
                    f"U+{cp:04X} {chr(cp)!r} duplicates U+{prev:04X} {chr(prev)!r}")
        seen.setdefault(key, cp)

    return sorted(glyphs.items()), parse(NOTDEF)


def preview():
    entries, notdef = build()
    for cp, cols in entries:
        try:
            name = chr(cp)
        except ValueError:
            name = '?'
        print(f"U+{cp:04X} {name!r}")
        for y in range(H):
            print('   ' + ''.join('#' if cols[x] & (1 << y) else '.' for x in range(W)))
    print(f"\n{len(entries)} glyphs, {len(entries) * W} bytes of glyph data")


def emit():
    entries, notdef = build()
    out = []
    w = out.append
    w("/*")
    w(" * ui_font_data.c — 5x7 glyph table.")
    w(" *")
    w(" * GENERATED by test/gen_font.py, DO NOT HAND-EDIT. Edit the ASCII art in")
    w(" * that script and regenerate; it can also print every glyph back with")
    w(" * --preview, which is the only sane way to review a font.")
    w(" *")
    w(" * Coverage is ASCII plus Cyrillic — the latter is not optional, since most")
    w(" * real Telegram traffic on this device will be Russian, and a Latin-only")
    w(" * font renders it as a wall of placeholder boxes.")
    w(" *")
    w(" * Column-major, 5 bytes per glyph, bit 0 = top row. The table is sorted by")
    w(" * codepoint so lookup is a binary search: the Cyrillic block sits far from")
    w(" * ASCII, and a flat 0x450-entry array would waste most of a kilobyte.")
    w(" */")
    w('#include "ui_font.h"')
    w("")
    w(f"const uint8_t ui_font_notdef[UI_FONT_BYTES] = {{ "
      + ", ".join(f"0x{b:02X}" for b in notdef) + " };")
    w("")
    w("const ui_glyph_t ui_font_glyphs[] = {")
    for cp, cols in entries:
        data = ", ".join(f"0x{b:02X}" for b in cols)
        ch = chr(cp)
        label = ch if ch.isprintable() and ch != ' ' else 'space' if ch == ' ' else '?'
        w(f"    {{ 0x{cp:04X}, {{ {data} }} }},   /* {label} */")
    w("};")
    w("")
    w("const size_t ui_font_glyph_count = "
      "sizeof(ui_font_glyphs) / sizeof(ui_font_glyphs[0]);")
    return "\n".join(out) + "\n"


if __name__ == '__main__':
    if '--preview' in sys.argv:
        preview()
    else:
        sys.stdout.write(emit())
